def lathe(name, rings, sides=12):
    vs=[]
    for y,radius in rings:
        for i in range(sides):
            a=i*math.tau/sides;vs.append((math.cos(a)*radius,y,math.sin(a)*radius))
    fs=[tuple(reversed(range(sides))),tuple(range((len(rings)-1)*sides,len(rings)*sides))]
    for row in range(len(rings)-1):
        for i in range(sides):
            j=(i+1)%sides;fs.append((row*sides+i,row*sides+j,(row+1)*sides+j,(row+1)*sides+i))
    return mesh(name,vs,fs)

