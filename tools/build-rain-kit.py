def mesh(name, vertices, faces, bevel=0):
    data = bpy.data.meshes.new('Rain Court / '+name)
    data.from_pydata([(x,-z,y) for x,y,z in vertices], [], faces)
    data.update()
    obj = bpy.data.objects.new(data.name, data); scene.collection.objects.link(obj)
    if bevel:
        mod = obj.modifiers.new('Hand cut edges', 'BEVEL'); mod.width=bevel; mod.segments=1
        mod.affect='EDGES'
    bpy.context.view_layer.update()
    evaluated=obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    final=evaluated.to_mesh(); final.calc_loop_triangles()
    p=[]
    for tri in final.loop_triangles:
        a,b,c=[final.vertices[i].co for i in tri.vertices]
        if (b-a).cross(c-a).length < .0000001: continue
        for index in tri.vertices:
            v=final.vertices[index].co; p.extend([round(v.x*10000),round(v.z*10000),round(-v.y*10000)])
    kit[name]={'p':p}
    evaluated.to_mesh_clear()
    obj.location.x=len(kit)*2-8
    return obj

